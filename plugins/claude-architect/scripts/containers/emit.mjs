// Generate boundary-enforcement config for an existing linter.
//
// We deliberately do NOT implement import resolution. dependency-cruiser and
// import-linter already handle re-exports, barrel files, dynamic imports, path
// aliases and namespace packages — which is exactly where a hand-rolled checker
// dies. containers.yaml stays the source of truth; these files are generated
// artifacts and should be committed but never hand-edited.

import { basename } from 'node:path';

const rx = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const alt = (paths) => `^(${paths.map(rx).join('|')})/`;

export const TARGETS = {
  'dependency-cruiser': { file: '.dependency-cruiser.generated.cjs', languages: ['typescript', 'javascript'] },
  'import-linter': { file: '.importlinter.generated', languages: ['python'] },
};

export function targetForLanguage(language) {
  const found = Object.entries(TARGETS).find(([, t]) => t.languages.includes(language));
  return found ? found[0] : null;
}

// ---------------------------------------------------------------------------

function emitDependencyCruiser(model) {
  const { containers, policy } = model;
  const rules = [];

  for (const c of containers) {
    const allowed = model.allowed(c.id);
    const allowedIds = new Set(allowed.map((a) => a.id));
    const forbiddenTargets = containers.filter((o) => o.id !== c.id && !allowedIds.has(o.id));

    if (forbiddenTargets.length) {
      rules.push({
        name: `boundary-${c.id.replace(/\//g, '-')}`,
        severity: 'error',
        comment:
          `${c.id} may only consume: ${allowed.length ? [...allowedIds].join(', ') : '(nothing)'}. ` +
          `Adding an edge is a structural decision — update .wiki/containers.yaml and regenerate, ` +
          `do not work around this in code.`,
        from: { path: `^${rx(c.path)}/` },
        to: { path: alt(forbiddenTargets.map((o) => o.path)) },
      });
    }

    // Purity rules bind sub-paths INSIDE a container, so they are stricter than
    // the container's own edges: `orchestration/auth` may call `engine/token`,
    // but `orchestration/auth/domain` may not.
    for (const pure of policy.pure_paths) {
      const dir = `${c.path}/${pure}`;
      rules.push({
        name: `pure-${c.id.replace(/\//g, '-')}-${pure.replace(/\//g, '-')}`,
        severity: 'error',
        comment:
          `${c.id}/${pure} must not import anything outside itself — not even from its own ` +
          `container. Rules that need I/O belong one level up; if a rule needs data, take it ` +
          `as an argument.`,
        from: { path: `^${rx(dir)}/` },
        to: { path: `^${rx(policy.root)}/`, pathNot: `^${rx(dir)}/` },
      });
    }

    if (allowed.length) {
      rules.push({
        name: `surface-${c.id.replace(/\//g, '-')}`,
        severity: 'error',
        comment:
          `${c.id} must import its dependencies through their public surface ` +
          `(${policy.public_surface.join(', ')}), not by reaching into their internals.`,
        from: { path: `^${rx(c.path)}/` },
        to: {
          path: alt(allowed.map((a) => a.path)),
          pathNot: `^(${allowed.flatMap((a) => a.surface).map(rx).join('|')})$`,
        },
      });
    }
  }

  const body = `// GENERATED by claude-architect from .wiki/containers.yaml — do not edit.
// Regenerate: node <plugin>/scripts/containers.mjs emit dependency-cruiser
module.exports = ${JSON.stringify({
    forbidden: rules,
    options: {
      doNotFollow: { path: 'node_modules' },
      // Catches `import type { UserRow } from '../engine/...'` as a real edge.
      // Without it, invariant 5 (owned types) is unenforceable — a type can
      // cross two layers while no function call does.
      tsPreCompilationDeps: true,
      // Extensionless imports do not resolve without this, and an unresolved
      // import matches no rule — i.e. the gate silently passes everything.
      enhancedResolveOptions: {
        extensions: ['.ts', '.tsx', '.d.ts', '.js', '.jsx', '.mjs', '.cjs', '.json'],
      },
      exclude: { path: '\\.(test|spec)\\.[jt]sx?$' },
    },
  }, null, 2)};
`;
  return { file: TARGETS['dependency-cruiser'].file, body, ruleCount: rules.length };
}

