function emitImportLinter(model) {
  const { containers, layers, policy } = model;
  const pkg = basename(policy.root);
  const mod = (path) => path.split('/').join('.').replace(/^[^.]+\./, `${pkg}.`);

  const out = [
    '# GENERATED by claude-architect from .wiki/containers.yaml — do not edit.',
    '# Regenerate: node <plugin>/scripts/containers.mjs emit import-linter',
    '',
    '[importlinter]',
    `root_package = ${pkg}`,
    '',
    '[importlinter:contract:layer-direction]',
    'name = Layer dependency direction (top may import bottom, never the reverse)',
    'type = layers',
    'layers =',
    ...layers.map((l) => `    ${pkg}.${l.id}`),
    '',
  ];

  let contracts = 1;
  const notes = [];
  for (const c of containers) {
    const allowedIds = new Set(model.allowed(c.id).map((a) => a.id));
    const forbidden = containers.filter((o) => o.id !== c.id && !allowedIds.has(o.id));
    const slug = c.id.replace(/[^A-Za-z0-9]+/g, '-');

    if (forbidden.length) {
      contracts += 1;
      out.push(
        `[importlinter:contract:${slug}]`,
        `name = ${c.id} allowed edges`,
        'type = forbidden',
        'source_modules =',
        `    ${mod(c.path)}`,
        'forbidden_modules =',
        ...forbidden.map((o) => `    ${mod(o.path)}`),
        '',
      );
    }

    // Purity: the cross-container half only. import-linter's `forbidden`
    // contract takes an explicit module list, so "imports nothing outside
    // itself" is expressible against other containers but not against the rest
    // of its OWN container without relying on descendant-matching semantics we
    // have not verified. The dependency-cruiser emitter enforces both halves.
    for (const pure of policy.pure_paths) {
      const others = containers.filter((o) => o.id !== c.id);
      if (!others.length) continue;
      contracts += 1;
      notes.push(`${c.id}/${pure}`);
      out.push(
        `[importlinter:contract:${slug}-pure-${pure.replace(/[^A-Za-z0-9]+/g, '-')}]`,
        `name = ${c.id}/${pure} is pure (no cross-container imports)`,
        'type = forbidden',
        'source_modules =',
        `    ${mod(`${c.path}/${pure}`)}`,
        'forbidden_modules =',
        ...others.map((o) => `    ${mod(o.path)}`),
        '',
      );
    }
  }

  if (notes.length) {
    out.splice(2, 0,
      '# NOTE: pure_paths contracts below cover CROSS-CONTAINER imports only.',
      '# The "no imports from the rest of its own container" half is enforced by the',
      '# dependency-cruiser emitter but not here — see docs/procedures/containers.md.',
    );
  }

  return { file: TARGETS['import-linter'].file, body: out.join('\n'), ruleCount: contracts };
}

// ---------------------------------------------------------------------------

export function emit(model, target) {
  switch (target) {
    case 'dependency-cruiser': return emitDependencyCruiser(model);
    case 'import-linter': return emitImportLinter(model);
    default:
      throw new Error(`unknown emit target \`${target}\` — expected one of ${Object.keys(TARGETS).join(', ')}`);
  }
}
